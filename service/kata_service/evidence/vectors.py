"""Fixture runner for evidence verifiers.

A vector names a source, a material object, an instant, and the expected
fields of the last result. ``repeat`` runs the same material more than once
so a replay vector can expect the second result. Ed25519 and ES256 tokens are
generated by the tests, not stored here.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from kata_service.evidence.schema import parse_evidence
from kata_service.evidence.store import EvidenceStore
from kata_service.evidence.verifier import utc_seconds, verifier_for

VECTORS = Path(__file__).resolve().parents[3] / "evidence" / "vectors" / "synthetic.json"


def load_vectors(path: Path | None = None) -> list[dict[str, Any]]:
    document = json.loads((path or VECTORS).read_text(encoding="utf-8"))
    if document.get("version") != 1 or not isinstance(document.get("vectors"), list):
        raise ValueError("vector file must be version 1 with a vectors array")
    return list(document["vectors"])


def _now(value: str) -> datetime:
    parsed = datetime.strptime(value, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)
    return utc_seconds(parsed)


def run_vector(vector: dict[str, Any], store: EvidenceStore, **deps: Any) -> list[dict[str, Any]]:
    """Run one vector. The returned list is one evidence object per attempt."""

    count = vector.get("repeat") or 1
    if isinstance(count, bool) or not isinstance(count, int) or count < 1:
        raise ValueError("repeat must be a positive integer")
    verifier = verifier_for(str(vector.get("source") or ""), store, **deps)
    moment = _now(str(vector.get("now") or ""))
    results = []
    for _ in range(count):
        evidence = verifier.verify(vector.get("material") or {}, now=moment)
        results.append(parse_evidence(evidence))
    return results
